import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const api = readFileSync(resolve(root, "src/api.ts"), "utf8");
const types = readFileSync(resolve(root, "src/types.ts"), "utf8");
const schema = readFileSync(resolve(root, "src/schema.ts"), "utf8");

assert.match(schema, /This file was auto-generated by openapi-typescript/);
assert.match(api, /createApiClient<paths>/, "客户门户 API 必须使用生成的 paths 客户端");
assert.doesNotMatch(api, /requestJson|\bfetch\s*\(/, "客户门户 API 不得绕过 api-client");
assert.doesNotMatch(api, /path:\s*`/, "客户门户 API 不得拼接 HTTP 路径");
assert.match(types, /components\["schemas"\]\["OrderSummary"\]/, "业务类型必须来自生成 schema");
console.log("customer portal api-client self-check passed");
