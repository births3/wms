import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const appShell = readFileSync(resolve(root, "src/App.tsx"), "utf8");
const viewRenderer = readFileSync(resolve(root, "src/app-shell/AdminViewRenderer.tsx"), "utf8");
const adminView = readFileSync(resolve(root, "src/app-shell/admin-view.ts"), "utf8");
const page = readFileSync(resolve(root, "src/pages/inventory/M3ReplenishmentStrategyPage.tsx"), "utf8");
const queries = readFileSync(resolve(root, "src/features/replenishment/replenishment-strategy-queries.ts"), "utf8");
const devMock = readFileSync(resolve(root, "dev-mocks/admin-menu-dev-mock.ts"), "utf8");
const pageQuery = readFileSync(resolve(root, "src/pages/page-query-core-fields.json"), "utf8");

assert.match(adminView, /"m3-replenishment-strategies"/, "AdminView 应包含 m3-replenishment-strategies");
assert.match(appShell, /id:\s*"m3-replenishment-strategies"/, "菜单应登记 m3-replenishment-strategies");
assert.match(viewRenderer, /m3-replenishment-strategies/, "视图渲染器应覆盖 m3-replenishment-strategies");
assert.match(viewRenderer, /M3ReplenishmentStrategyPage/, "视图渲染器应挂载 M3ReplenishmentStrategyPage");
assert.match(devMock, /m3-replenishment-strategies/, "dev mock 菜单应包含 m3-replenishment-strategies");
assert.match(pageQuery, /"id":\s*"m3-replenishment-strategies"/, "查询面板配置应登记 m3-replenishment-strategies");
assert.match(pageQuery, /"core":\s*\[[^\]]*keyword[^\]]*enabled/, "核心查询应含 keyword、enabled");
assert.match(pageQuery, /"more":\s*\[[^\]]*scope_type[^\]]*target_type/, "更多查询应含 scope_type、target_type");
assert.match(page, /(?:<DataGrid\b|<ListPageTemplate\b)/, "补货策略页必须使用公共 DataGrid 或 ListPageTemplate");
assert.match(page, /(?:<QueryPanel\b|<ListPageTemplate\b)/, "补货策略页必须使用公共 QueryPanel 或 ListPageTemplate");
assert.match(page, /<Dialog\b/, "补货策略写操作必须使用 Dialog");
assert.match(page, /基本信息/, "配置型分区应含基本信息");
assert.match(page, /动线与 scope|动线与范围/, "配置型分区应含动线与 scope");
assert.match(page, /Min-Max 与触发模式/, "配置型分区应含 Min-Max 与触发模式");
assert.match(page, /挂接拣选位/, "配置型分区应含挂接拣选位");
assert.match(page, /启停/, "配置型分区应含启停");
assert.match(page, /命中预览/, "配置型分区应含命中预览");
assert.doesNotMatch(queries, /\bfetch\s*\(/, "补货策略查询必须统一使用生成的 api-client");
assert.match(queries, /api\.GET\("\/api\/v1\/replenishment\/strategies"/, "读取必须使用策略列表 API");
assert.match(queries, /api\.POST\("\/api\/v1\/replenishment\/strategies"/, "保存必须使用策略创建 API");
assert.match(queries, /api\.PUT\("\/api\/v1\/replenishment\/strategies\/\{id\}"/, "更新必须使用策略更新 API");
assert.match(queries, /api\.GET\("\/api\/v1\/replenishment\/strategies\/\{id\}\/preview"/, "预览必须使用命中预览 API");
assert.match(queries, /api\.PUT\("\/api\/v1\/replenishment\/strategies\/\{id\}\/locations"/, "挂接必须使用库位绑定 API");
assert.match(queries, /api\.POST\("\/api\/v1\/replenishment\/location-groups"/, "库位组必须使用组维护 API");
assert.match(queries, /Idempotency-Key/, "写入必须携带幂等键");
assert.match(page, /queryStringArray/, "multiSelect 必须用 queryStringArray 下推");
assert.match(page, /queryStringArray\(query\.enabled\)/, "enabled 多选必须下推");
assert.match(page, /queryStringArray\(query\.scope_type\)/, "scope_type 多选必须下推");
assert.match(page, /queryStringArray\(query\.target_type\)/, "target_type 多选必须下推");
assert.doesNotMatch(page, /enabled:\s*queryString\(query\.enabled\)/, "enabled 不得被 queryString 吞成空串");
console.log("m3 replenishment strategy self-check passed");
