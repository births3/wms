import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const appShell = readFileSync(resolve(root, "src/App.tsx"), "utf8");
const viewRenderer = readFileSync(resolve(root, "src/app-shell/AdminViewRenderer.tsx"), "utf8");
const adminView = readFileSync(resolve(root, "src/app-shell/admin-view.ts"), "utf8");
const page = readFileSync(resolve(root, "src/pages/inventory/M3ReplenishmentTaskPage.tsx"), "utf8");
const queries = readFileSync(resolve(root, "src/features/replenishment/replenishment-task-queries.ts"), "utf8");
const devMock = readFileSync(resolve(root, "dev-mocks/admin-menu-dev-mock.ts"), "utf8");
const pageQuery = readFileSync(resolve(root, "src/pages/page-query-core-fields.json"), "utf8");

assert.match(adminView, /"m3-replenishment-tasks"/, "AdminView 应包含 m3-replenishment-tasks");
assert.match(appShell, /id:\s*"m3-replenishment-tasks"/, "菜单应登记 m3-replenishment-tasks");
assert.match(viewRenderer, /m3-replenishment-tasks/, "视图渲染器应覆盖 m3-replenishment-tasks");
assert.match(viewRenderer, /M3ReplenishmentTaskPage/, "视图渲染器应挂载 M3ReplenishmentTaskPage");
assert.match(devMock, /m3-replenishment-tasks/, "dev mock 菜单应包含 m3-replenishment-tasks");
assert.match(pageQuery, /"id":\s*"m3-replenishment-tasks"/, "查询面板配置应登记 m3-replenishment-tasks");
assert.match(pageQuery, /"core":\s*\[[^\]]*status[^\]]*trigger_mode/, "核心查询应含 status、trigger_mode");
assert.match(page, /(?:<DataGrid\b|<ListPageTemplate\b)/, "补货任务大盘必须使用公共 DataGrid 或 ListPageTemplate");
assert.match(page, /(?:<QueryPanel\b|<ListPageTemplate\b)/, "补货任务大盘必须使用公共 QueryPanel 或 ListPageTemplate");
assert.match(page, /<Dialog\b/, "私有动作必须使用 Dialog");
assert.match(page, /任务号/, "固定列应含任务号");
assert.match(page, /触发模式/, "固定列应含触发模式");
assert.match(page, /优先级/, "固定列应含优先级");
assert.match(page, /来源位/, "固定列应含来源位");
assert.match(page, /目标位/, "固定列应含目标位");
assert.match(page, /手动发起/, "私有动作应含手动发起");
assert.match(page, /重派/, "私有动作应含重派");
assert.match(page, /取消/, "私有动作应含取消");
assert.doesNotMatch(page, /策略编码|Min-Max 与触发模式/, "大盘不得夹带策略 CRUD 表单");
assert.doesNotMatch(queries, /\bfetch\s*\(/, "补货任务查询必须统一使用生成的 api-client");
assert.match(queries, /api\.GET\("\/api\/v1\/replenishment\/tasks"/, "列表必须使用任务列表 API");
assert.match(queries, /api\.POST\("\/api\/v1\/replenishment\/tasks"/, "手工发起必须使用任务创建 API");
assert.match(queries, /api\.POST\("\/api\/v1\/replenishment\/tasks\/\{id\}\/cancel"/, "取消必须使用取消 API");
assert.match(queries, /api\.POST\("\/api\/v1\/replenishment\/tasks\/\{id\}\/reassign"/, "重派必须使用改派 API");
assert.match(queries, /Idempotency-Key/, "写入必须携带幂等键");
console.log("m3 replenishment task self-check passed");
